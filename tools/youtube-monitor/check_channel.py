#!/usr/bin/env python3
"""Check a YouTube channel for videos the hymnal has not accounted for yet.

Lists every video of the channel (yt-dlp, flat, one request) and compares it with
  * the matched recordings (databaseProvisioner/src/main/resources/NycypcdYoutube.txt: hymn id TAB video id), and
  * the known leftovers (nycypcd_known.tsv: songs not in the database, unavailable videos, non-songs).
Anything else is new (a new album or a song we missed): run the match-youtube-songs skill on it.

  python3 tools/youtube-monitor/check_channel.py [--ytdlp PATH] [--videos videos.txt] [--json out.json]

With --releases it also lists the channel's Releases tab (albums, auto-generated audio uploads in every language,
not in the Videos tab) and every track of every album, cached in nycypcd_releases.tsv (album id, album, video id, track,
seconds), with a pause between albums. Releases tracks count as accounted for once they are in NycypcdYoutube.txt or
nycypcd_known.tsv, like videos.

Exit code 0 = everything accounted for, 1 = new or unaccounted videos, 2 = could not list the channel.
--videos reads a saved list (lines "id|title|duration") instead of calling yt-dlp.
"""
import argparse, os, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
CHANNEL = "UC_1giUVT14MRXyEFtQZgmKQ"  # NYCYPCD, linked from nycypcd.org
MATCHED = os.path.join(REPO, "databaseProvisioner/src/main/resources/NycypcdYoutube.txt")
KNOWN = os.path.join(HERE, "nycypcd_known.tsv")


def tsv(path):
    for line in open(path, encoding="utf8"):
        if line.strip() and not line.startswith("#"):
            yield line.rstrip("\n").split("\t")


def list_channel(ytdlp, channel):
    cmd = [ytdlp, "--flat-playlist", "--print", "%(id)s|%(title)s|%(duration)s",
           "--socket-timeout", "30", f"https://www.youtube.com/channel/{channel}/videos"]
    r = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
    if r.returncode != 0 or not r.stdout.strip():
        sys.exit("could not list the channel (rate limit or network?): " + r.stderr.strip()[-300:] + "\n") or 2
    return r.stdout


def list_releases(ytdlp, handle, cache, pause=4):
    """Albums of the Releases tab and their tracks -> cache TSV (resumable: albums already in it are kept)."""
    import time
    def run(url, fmt):
        r = subprocess.run([ytdlp, "--flat-playlist", "--print", fmt, "--socket-timeout", "30", url],
                           capture_output=True, text=True, timeout=300)
        return r.stdout.splitlines() if r.returncode == 0 else None
    albums = run(f"https://www.youtube.com/@{handle}/releases", "%(id)s|%(title)s")
    if not albums:
        raise OSError("could not list the Releases tab")
    done = {}
    if os.path.exists(cache):
        for r in tsv(cache):
            done.setdefault(r[0], []).append(r)
    for line in albums:
        aid, title = line.split("|", 1)
        if aid in done:
            continue
        time.sleep(pause)
        tr = run(f"https://www.youtube.com/playlist?list={aid}", "%(id)s|%(title)s|%(duration)s")
        if tr is None:
            print("  (album failed, will retry next run):", title, file=sys.stderr)
            continue
        done[aid] = [[aid, title] + t.split("|") for t in tr]
        with open(cache, "w", encoding="utf8") as f:
            f.write("# album id, album, video id, track, seconds (generated by check_channel.py --releases)\n")
            for rows in done.values():
                for r in rows:
                    f.write("\t".join(r) + "\n")
    return [r for rows in done.values() for r in rows]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--channel", default=CHANNEL)
    ap.add_argument("--ytdlp", default=shutil.which("yt-dlp") or "yt-dlp")
    ap.add_argument("--videos", help="saved list instead of calling yt-dlp")
    ap.add_argument("--releases", action="store_true", help="also check the Releases tab (slow: one request per album)")
    ap.add_argument("--handle", default="NYCYPCD")
    ap.add_argument("--json")
    a = ap.parse_args()

    try:
        raw = open(a.videos, encoding="utf8").read() if a.videos else list_channel(a.ytdlp, a.channel)
    except (OSError, subprocess.SubprocessError) as e:
        print("could not list the channel:", e, file=sys.stderr)
        return 2
    channel = {}
    for line in raw.splitlines():
        p = line.split("|")
        if len(p) >= 2 and len(p[0]) == 11:
            channel[p[0]] = (p[1], p[2] if len(p) > 2 else "")

    tracks = []
    if a.releases:
        try:
            tracks = list_releases(a.ytdlp, a.handle, os.path.join(HERE, "nycypcd_releases.tsv"))
        except (OSError, subprocess.SubprocessError) as e:
            print("could not list releases:", e, file=sys.stderr)
            return 2
        for r in tracks:
            channel.setdefault(r[2], (f"[{r[1]}] {r[3]}", r[4] if len(r) > 4 else ""))
        print(f"releases: {len(set(r[0] for r in tracks))} albums, {len(set(r[2] for r in tracks))} distinct tracks")

    matched = {r[1]: r[0] for r in tsv(MATCHED) if len(r) >= 2}
    known = {r[0]: (r[1], r[2] if len(r) > 2 else "") for r in tsv(KNOWN)}

    on_matched = [v for v in channel if v in matched]
    on_known = [v for v in channel if v in known and v not in matched]
    new = [v for v in channel if v not in matched and v not in known]
    gone = [v for v in list(matched) + list(known) if v not in channel]

    print(f"channel {a.channel}: {len(channel)} videos")
    print(f"  matched to a hymn (link table): {len(on_matched)}")
    for st in sorted({known[v][0] for v in on_known}):
        print(f"  {st}: {sum(1 for v in on_known if known[v][0] == st)}")
    print(f"  NEW / not accounted for: {len(new)}")
    for v in new:
        print(f"    https://www.youtube.com/watch?v={v}  {channel[v][0]}")
    if gone:
        print(f"  accounted for but no longer on the channel: {len(gone)}")
        for v in gone:
            print(f"    {v}  {matched.get(v) or known[v][1]}")
    dups = len(matched) - len(set(matched.values()))
    if a.json:
        import json
        json.dump({"channel": len(channel), "new": [{"id": v, "title": channel[v][0]} for v in new],
                   "gone": gone}, open(a.json, "w"), indent=1)
    return 1 if new else 0


if __name__ == "__main__":
    sys.exit(main())
